import assert from 'node:assert/strict';
import {normalize,total,bundle} from './catalog.mjs';
assert.deepEqual(normalize(null),[]);
assert.deepEqual(normalize([{product:'bogus',qty:1},{product:'one',finish:'bogus',qty:1}]),[]);
assert.equal(total(bundle('one','silver')),34900);
assert.equal(total(bundle('one','cobalt',['stand','case'])),43700);
assert.equal(total(bundle('one','cobalt',['stand','stand'])),39800);
assert.equal(total(bundle('mini','graphite',['stand','case'])),17900);
assert.equal(normalize([{product:'one',finish:'silver',qty:8},{product:'one',finish:'silver',qty:9}])[0].qty,10);
assert.equal(total([{product:'one',finish:'silver',qty:2},{product:'mini',finish:'cobalt',qty:1}]),87700);
assert.deepEqual(normalize([{product:'one',finish:'silver',qty:-1}]),[]);
assert.equal(normalize([{product:'case',qty:1.9}])[0].qty,1);
console.log('10 commerce checks passed.');
assert.equal(total(bundle('buds','silver')),14900);
assert.equal(total(bundle('headphones','graphite')),27900);
assert.equal(total(bundle('dock','cobalt',['stand','case'])),8900);
assert.equal(total([...bundle('buds','silver'),...bundle('headphones','graphite'),...bundle('dock','cobalt')]),51700);
assert.equal(normalize([{product:'buds',finish:'silver',qty:1},{product:'buds',finish:'cobalt',qty:1}]).length,2);
console.log('5 expanded-device commerce checks passed.');
